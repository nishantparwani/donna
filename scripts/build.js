// Build step: embeds the Apps Script bridge (with its token replaced by a placeholder) so the app can
// hand you a ready-to-paste copy with YOUR token filled in, and renders the app icons as PNGs.
import fs from 'node:fs';
import zlib from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const code = fs.readFileSync(path.join(ROOT, 'bridge', 'Code.gs'), 'utf8').replace(/const TOKEN = '[^']*';/, "const TOKEN = 'CHANGE_ME_to_a_long_random_text';");
const manifest = fs.readFileSync(path.join(ROOT, 'bridge', 'appsscript.json'), 'utf8');
fs.writeFileSync(path.join(ROOT, 'src', 'bridge-code.js'),
  `// Generated by scripts/build.js from bridge/ — do not edit by hand.\nexport const BRIDGE_CODE = ${JSON.stringify(code)};\nexport const BRIDGE_MANIFEST = ${JSON.stringify(manifest)};\n`);

// ─── Icons: indigo→violet rounded square with a white calendar check ───
function png(size) {
  const px = Buffer.alloc(size * size * 4);
  const r = size * 0.22;
  const inRound = (x, y) => {
    const cx = Math.min(Math.max(x, r), size - r), cy = Math.min(Math.max(y, r), size - r);
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r;
  };
  const segDist = (x, y, ax, ay, bx, by) => {
    const dx = bx - ax, dy = by - ay, t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)));
    return Math.hypot(x - (ax + t * dx), y - (ay + t * dy));
  };
  const s = size / 24;
  const w = 1.9 * s;
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const i = (y * size + x) * 4;
    if (!inRound(x + .5, y + .5)) { px[i + 3] = 0; continue; }
    const t = (x + y) / (2 * size);
    let R = 79 + (139 - 79) * t, G = 70 + (92 - 70) * t, B = 229 + (246 - 229) * t;
    const X = x / s, Y = y / s;
    // calendar outline + header line + check
    const box = (X > 5 && X < 19 && Y > 6.5 && Y < 19) && (Math.abs(X - 5.5) < .9 || Math.abs(X - 18.5) < .9 || Math.abs(Y - 7) < .9 || Math.abs(Y - 18.5) < .9 || Math.abs(Y - 10.5) < .8);
    const rings = (Math.abs(X - 9) < .9 || Math.abs(X - 15) < .9) && Y > 4.5 && Y < 8.5;
    const check = segDist(X, Y, 9, 14.2, 11, 16.2) * s < w * .55 || segDist(X, Y, 11, 16.2, 15.2, 12) * s < w * .55;
    if (box || rings || check) { R = G = B = 255; }
    px[i] = R; px[i + 1] = G; px[i + 2] = B; px[i + 3] = 255;
  }
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y++) { raw[y * (size * 4 + 1)] = 0; px.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4); }
  const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = b => { let c = 0xffffffff; for (const x of b) c = crcTable[(c ^ x) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([len, td, c]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}
for (const n of [192, 512]) fs.writeFileSync(path.join(ROOT, 'public', `icon-${n}.png`), png(n));
console.log('Built src/bridge-code.js and public/icon-*.png');
